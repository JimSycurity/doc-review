"""Generate stable directory navigation without taking over curated documents."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import PurePosixPath
from typing import TYPE_CHECKING
from urllib.parse import quote

from docreview.frontmatter import Finding, validate_document
from docreview.markdown import document_opening
from docreview.paths import maintained_paths, matches, repository_path

if TYPE_CHECKING:
    from docreview.configuration import ProjectConfig
    from docreview.documentation_decisions import Json

MARKER = "<!-- Generated by docreview catalog. Edit source pages, then regenerate. -->"


@dataclass(frozen=True)
class CatalogChange:
    """Keep the expected text and original snapshot together for safe application."""

    path: str
    expected: str
    previous: str | None
    conflict: bool = False

    @property
    def state(self) -> str:
        if self.conflict:
            return "conflict"
        return "current" if self.expected == self.previous else "stale"

    def as_json(self, mode: str, *, applied: bool) -> dict[str, Json]:
        written = applied and self.state == "stale"
        return {
            "path": self.path,
            "state": "current" if written else self.state,
            "action": "written" if written else "none",
            **({"content": self.expected} if mode == "report-only" else {}),
        }


@dataclass(frozen=True)
class CatalogPlan:
    """Describe all changes before writing any file."""

    changes: tuple[CatalogChange, ...]
    failures: tuple[tuple[str, Finding], ...] = ()

    @property
    def has_failures(self) -> bool:
        return bool(self.failures) or any(
            change.state != "current" for change in self.changes
        )

    def as_json(self, mode: str, *, applied: bool = False) -> dict[str, Json]:
        return {
            "mode": mode,
            "catalogs": [
                change.as_json(mode, applied=applied) for change in self.changes
            ],
            "failures": [
                {"path": path, **failure.as_json()} for path, failure in self.failures
            ],
        }


def _is_target(config: ProjectConfig, path: str) -> bool:
    return (
        path != "README.md"
        and matches(path, config.generated)
        and matches(path, config.maintained)
        and not matches(path, config.excluded)
    )


def _targets(config: ProjectConfig, paths: list[str]) -> set[str]:
    result = set()
    for path in paths:
        parent = PurePosixPath(path).parent
        for directory in (parent, *parent.parents):
            target = (directory / "README.md").as_posix()
            if _is_target(config, target):
                result.add(target)
    return result


def _cell(value: str) -> str:
    return " ".join(value.split()).replace("|", "\\|")


def _label(value: str) -> str:
    return _cell(value).replace("[", "\\[").replace("]", "\\]")


def _entry(
    config: ProjectConfig, path: str, text: str
) -> tuple[str, tuple[Finding, ...]]:
    declaration = validate_document(config, path, text)
    title, purpose = document_opening(text, declaration.body_start)
    link = quote(PurePosixPath(path).name, safe="._-")
    row = f"| [{_label(title)}]({link}) | {_cell(declaration.document_type or 'unknown')} | {_cell(declaration.status or '-')} | {_cell(purpose)} |"
    return row, declaration.failures


def _render(path: str, entries: list[str], targets: set[str]) -> str:
    parent = PurePosixPath(path).parent
    children = sorted(
        target for target in targets if PurePosixPath(target).parent.parent == parent
    )
    lines = [
        MARKER,
        "",
        f"# {parent.name} documentation",
        "",
        "Read when finding documentation in this directory.",
        "",
    ]
    if entries:
        lines.extend(
            [
                "| Document | Type | Status | Purpose |",
                "| --- | --- | --- | --- |",
                *entries,
                "",
            ]
        )
    if children:
        lines.extend(
            [
                "## Directories",
                "",
                *[
                    f"- [{_label(PurePosixPath(child).parent.name)}]({quote(PurePosixPath(child).relative_to(parent).as_posix(), safe='/._-')})"
                    for child in children
                ],
                "",
            ]
        )
    return "\n".join(lines)


def plan_catalogs(config: ProjectConfig) -> CatalogPlan:
    """Read only the maintained corpus and declared generated paths."""
    paths = maintained_paths(config)
    targets = _targets(config, paths)
    changes = []
    failures = []
    for target in sorted(targets):
        if matches(target, config.curated):
            if not repository_path(config.root, target).is_file():
                failures.append(
                    (
                        target,
                        Finding(
                            "catalog.curated_missing",
                            1,
                            1,
                            "the configured curated index is missing; its owner must supply the routing page",
                        ),
                    )
                )
            continue
        entries = []
        for path in paths:
            if PurePosixPath(path).parent != PurePosixPath(target).parent or matches(
                path, config.generated
            ):
                continue
            row, problems = _entry(
                config,
                path,
                repository_path(config.root, path).read_text(encoding="utf-8"),
            )
            entries.append(row)
            failures.extend((path, problem) for problem in problems)
        file = repository_path(config.root, target)
        previous = file.read_text(encoding="utf-8") if file.exists() else None
        conflict = file.is_symlink() or (
            previous is not None and not previous.startswith(MARKER + "\n")
        )
        if conflict:
            failures.append(
                (
                    target,
                    Finding(
                        "catalog.ownership",
                        1,
                        1,
                        "an existing unmarked README is not generated output; preserve it and ask its owner to declare curated routing or approve conversion",
                    ),
                )
            )
        changes.append(
            CatalogChange(target, _render(target, entries, targets), previous, conflict)
        )
    return CatalogPlan(tuple(changes), tuple(failures))


def apply_catalogs(config: ProjectConfig, plan: CatalogPlan) -> None:
    """Refuse contributed writes and conflicts before changing any catalog."""
    if config.authority != "owned":
        raise ValueError("contributed mode forbids catalog writes")
    if plan.failures:
        raise ValueError("catalog plan has unresolved findings")
    for change in plan.changes:
        file = repository_path(config.root, change.path)
        current = file.read_text(encoding="utf-8") if file.exists() else None
        if file.is_symlink() or current != change.previous:
            raise ValueError("catalog changed after inspection; inspect again")
    for change in plan.changes:
        if change.state == "stale":
            repository_path(config.root, change.path).write_text(
                change.expected, encoding="utf-8"
            )
